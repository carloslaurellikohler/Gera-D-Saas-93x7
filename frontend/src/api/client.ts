export async function apiDelete(path: string): Promise<void> {
  const response = await fetch(`${API_BASE_URL}${path}`, {
    method: "DELETE",
    credentials: "include",
  });
  await handleResponse<void>(response);
}

export function reportUrl(analysisId: string, kind: "executivo" | "detalhado"): string {
  return `${API_BASE_URL}/analyses/${analysisId}/report?kind=${kind}`;
}
